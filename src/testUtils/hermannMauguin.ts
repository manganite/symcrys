/**
 * Reading a Hermann–Mauguin symbol into a group, independently of the library (test-only code):
 * each position of the symbol names the symmetry elements along one Cartesian direction (an axis
 * `N` or `-N`, a mirror normal `m`, or both, `N/m`; `1` names none).
 */

import { close, mirrorNormal, neg, rotationAbout, type M, type RefOp } from './independentGroups.js';

/** The positions of a symbol: `N`, `-N`, `N/m`, `m`; spaces are ignored. */
export function hmTokens(hm: string): string[] {
  const compact = hm.replace(/\s+/g, '');
  const list = compact.match(/-?[1-6](\/m)?|m/g) ?? [];
  if (list.join('') !== compact) throw new Error(`Unreadable symbol: ${hm}`);
  return list;
}

/** Generators of one position along the Cartesian direction u. */
function positionGenerators(token: string, u: number[]): M[] {
  if (token === 'm') return [mirrorNormal(u)];
  const m = /^(-?)([1-6])(\/m)?$/.exec(token);
  if (!m) throw new Error(`Unreadable position: ${token}`);
  const rotation = rotationAbout(u, 1 / Number(m[2]));
  const gens = [m[1] ? neg(rotation) : rotation];
  if (m[3]) gens.push(mirrorNormal(u));
  return gens;
}

/** The group generated by the symbol, its positions taken along `directions` (Cartesian) in order. */
export function groupOfSymbol(hm: string, directions: number[][]): RefOp[] {
  const list = hmTokens(hm);
  if (list.length > directions.length) throw new Error(`${hm}: more positions than directions`);
  const gens = list.flatMap((t, i) => (t === '1' ? [] : positionGenerators(t, directions[i])));
  return close(gens.map((m) => ({ m, t: false })));
}
