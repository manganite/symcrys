/**
 * Independent matrix algebra for the reference tests (test-only code). Deliberately shares nothing
 * with the library (no import from src/ outside testUtils), so an error in the library's linear
 * algebra, closure or data cannot cancel out in a comparison (CLAUDE.md, "Anti-circularity").
 */

export type M = number[][];

/** A matrix with its time-reversal flag. */
export interface RefOp {
  m: M;
  t: boolean;
}

const TOL = 1e-6;
const SNAP = [0, 1, -1, 0.5, -0.5, Math.sqrt(0.5), -Math.sqrt(0.5), Math.sqrt(3) / 2, -Math.sqrt(3) / 2];

export const I3: M = [
  [1, 0, 0],
  [0, 1, 0],
  [0, 0, 1],
];

export function mul(a: M, b: M): M {
  return [0, 1, 2].map((i) => [0, 1, 2].map((j) => a[i][0] * b[0][j] + a[i][1] * b[1][j] + a[i][2] * b[2][j]));
}

function snapM(a: M): M {
  return a.map((row) => row.map((v) => SNAP.find((s) => Math.abs(v - s) < 1e-9) ?? v));
}

export function sameM(a: M, b: readonly (readonly number[])[]): boolean {
  return [0, 1, 2].every((i) => [0, 1, 2].every((j) => Math.abs(a[i][j] - b[i][j]) < TOL));
}

/** Inverse of a 3×3 matrix (by the adjugate). */
export function inverse(a: M): M {
  const c = (i: number, j: number) => {
    const r = [0, 1, 2].filter((k) => k !== i);
    const s = [0, 1, 2].filter((k) => k !== j);
    return a[r[0]][s[0]] * a[r[1]][s[1]] - a[r[0]][s[1]] * a[r[1]][s[0]];
  };
  const det = a[0][0] * c(0, 0) - a[0][1] * c(0, 1) + a[0][2] * c(0, 2);
  return [0, 1, 2].map((i) => [0, 1, 2].map((j) => ((i + j) % 2 === 0 ? 1 : -1) * (c(j, i) / det)));
}

/** Proper rotation by `turns` × 360° about the axis `u` (any length), by Rodrigues' formula. */
export function rotationAbout(u: number[], turns: number): M {
  const n = Math.hypot(u[0], u[1], u[2]);
  const [x, y, z] = u.map((v) => v / n);
  const a = 2 * Math.PI * turns;
  const c = Math.cos(a);
  const s = Math.sin(a);
  const t = 1 - c;
  return [
    [t * x * x + c, t * x * y - s * z, t * x * z + s * y],
    [t * x * y + s * z, t * y * y + c, t * y * z - s * x],
    [t * x * z - s * y, t * y * z + s * x, t * z * z + c],
  ];
}

export const neg = (a: M): M => a.map((row) => row.map((v) => -v));

/** Mirror with normal `u`: the inversion times the twofold rotation about `u`. */
export const mirrorNormal = (u: number[]): M => neg(rotationAbout(u, 1 / 2));

/** The closed group generated by `gens`. */
export function close(gens: RefOp[]): RefOp[] {
  const group: RefOp[] = [{ m: I3, t: false }];
  const add = (op: RefOp) => {
    if (group.some((g) => g.t === op.t && sameM(g.m, op.m))) return;
    if (group.length > 200) throw new Error('reference closure does not terminate');
    group.push(op);
  };
  for (const g of gens) add({ m: snapM(g.m), t: g.t });
  for (let i = 0; i < group.length; i++) {
    for (let j = 0; j < group.length; j++) {
      add({ m: snapM(mul(group[i].m, group[j].m)), t: group[i].t !== group[j].t });
    }
  }
  return group;
}

/** Set equality of a reference group and any list of operations with a matrix and a time-reversal flag. */
export function sameGroup(
  ref: RefOp[],
  ops: readonly { readonly matrix: readonly (readonly number[])[]; readonly timeReversal: boolean }[],
): boolean {
  if (ref.length !== ops.length) return false;
  return ref.every((r) => ops.some((o) => o.timeReversal === r.t && sameM(r.m, o.matrix)));
}
