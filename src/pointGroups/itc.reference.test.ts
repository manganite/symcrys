/**
 * ITC convention against its print sources (fixture class (b), calibrated against (a)).
 *
 * The expected ITC operations of every setting are derived independently of the library: the ITC
 * symbol of the setting (itcSettings.fixtures.ts, each printed row checked against the re-parsed
 * tables) is read position by position along the symmetry directions of ITA Table 2.1.3.1
 * (references/itc/vol-a-table-2.1.3.1.md), converted to Cartesian with the frame decided on #6
 * (x ∥ a, z ∥ c, y = z × x; typed here from the decision, not imported), and closed with the
 * independent algebra of testUtils.
 */

import { describe, expect, it } from 'vitest';
import {
  close,
  mirrorNormal,
  mul,
  neg,
  rotationAbout,
  sameGroup,
  type M,
  type RefOp,
} from '../testUtils/independentGroups.js';
import { expectHeader, readReference, tableRows } from '../testUtils/references.js';
import { ITC_SETTINGS } from './itcSettings.fixtures.js';
import { POINT_GROUP_KEYS, findPointGroup, operations, settings, type PointGroupKey } from './pointGroups.js';

// --- Lattice bases (the #6 decision, typed independently of src/lattice.ts) -------------------------

const ORTHONORMAL: M = [
  [1, 0, 0],
  [0, 1, 0],
  [0, 0, 1],
];
/** Columns a, b, c: a = x, b at 120° from a in the xy plane, c = z. */
const HEXAGONAL: M = [
  [1, -1 / 2, 0],
  [0, Math.sqrt(3) / 2, 0],
  [0, 0, 1],
];

// --- ITA Table 2.1.3.1 ------------------------------------------------------------------------------

const directionRows = tableRows(readReference('itc/vol-a-table-2.1.3.1.md'));
expectHeader(directionRows, ['Lattice', 'Primary', 'Secondary', 'Tertiary']);

/** First direction [uvw] in a cell, or undefined for an empty cell or "None". */
function firstDirection(cell: string): number[] | undefined {
  const m = /\[([-\d]+)\]/.exec(cell);
  if (!m) return undefined;
  return [...m[1].matchAll(/-?\d/g)].map((d) => Number(d[0]));
}

function latticeRow(name: string): string[] {
  const row = directionRows.find((r) => r[0] === name);
  if (!row) throw new Error(`Lattice ${name} not in Table 2.1.3.1`);
  return row;
}

/** Representative directions of the symbol positions, in lattice coordinates. */
function positions(lattice: string): number[][] {
  return latticeRow(lattice)
    .slice(1)
    .map(firstDirection)
    .filter((d): d is number[] => d !== undefined);
}

const MONOCLINIC = latticeRow('Monoclinic (a)')[1];
const MONOCLINIC_AXIS: Record<'b' | 'c', number[]> = {
  b: firstDirection(/(\[[-\d]+\]) \(unique axis b\)/.exec(MONOCLINIC)![1])!,
  c: firstDirection(/(\[[-\d]+\]) \(unique axis c\)/.exec(MONOCLINIC)![1])!,
};

// --- Symbols to generators ----------------------------------------------------------------------

/** Hermann–Mauguin positions: `N`, `-N`, `N/m`, `m`; spaces are ignored. */
function tokens(hm: string): string[] {
  const compact = hm.replace(/\s+/g, '');
  const list = compact.match(/-?[1-6](\/m)?|m/g) ?? [];
  if (list.join('') !== compact) throw new Error(`Unreadable symbol: ${hm}`);
  return list;
}

/** Generators of one position along the Cartesian direction u. */
function positionGenerators(token: string, u: number[]): M[] {
  const m = /^(-?)([1-6])(\/m)?$/.exec(token);
  if (token === 'm') return [mirrorNormal(u)];
  if (!m) throw new Error(`Unreadable position: ${token}`);
  const n = Number(m[2]);
  const rotation = rotationAbout(u, 1 / n);
  const gens = [m[1] ? neg(rotation) : rotation];
  if (m[3]) gens.push(mirrorNormal(u));
  return gens;
}

const toCartesian = (basis: M, d: number[]): number[] =>
  mul(
    basis,
    d.map((v) => [v]),
  ).map((r) => r[0]);

/**
 * Operations generated by an ITC symbol. `lattice` names the row of Table 2.1.3.1; for monoclinic
 * short symbols the single position is the unique axis.
 */
function generate(hm: string, system: string, uniqueAxis?: 'a' | 'b' | 'c'): RefOp[] {
  const list = tokens(hm);
  let dirs: number[][];
  let basis = ORTHONORMAL;
  if (system === 'triclinic')
    dirs = [[0, 0, 1]]; // only 1 or -1, which need no direction
  else if (system === 'monoclinic' && list.length === 1) dirs = [MONOCLINIC_AXIS[uniqueAxis as 'b' | 'c']];
  else if (system === 'monoclinic' || system === 'orthorhombic') dirs = positions('Orthorhombic');
  else if (system === 'tetragonal') dirs = positions('Tetragonal');
  else if (system === 'trigonal' || system === 'hexagonal') {
    dirs = positions('Hexagonal');
    basis = HEXAGONAL;
  } else dirs = positions('Cubic');
  if (list.length > dirs.length) throw new Error(`${hm}: more positions than symmetry directions`);
  const gens = list.flatMap((t, i) => (t === '1' ? [] : positionGenerators(t, toCartesian(basis, dirs[i]))));
  return close(gens.map((m) => ({ m, t: false })));
}

// --- Print rows behind the fixture --------------------------------------------------------------

/** Class symbols of ITA Table 2.1.1.1, without the box markers. */
function table2111Symbols(): string[] {
  const rows = tableRows(readReference('itc/vol-a-table-2.1.1.1.md'));
  expect(rows[0][3]).toBe('Crystallographic point groups');
  return rows
    .slice(1)
    .flatMap((r) => r[3].split(','))
    .map((s) => s.replace(/\((L|H)\)/, '').trim())
    .filter((s) => s !== '');
}

/** Class column of Table 3.2.2.2 (hexagonal axes for trigonal; rhombohedral rows left out), with the unique axis. */
function table3222Classes(): { short: string; uniqueAxis?: 'b' | 'c' }[] {
  const rows = tableRows(readReference('itc/table-3.2.2.2.md'));
  expectHeader(rows, ['System', 'Class', 'Polar (symmetry) axes', 'Nonpolar directions']);
  let system = '';
  const out: { short: string; uniqueAxis?: 'b' | 'c' }[] = [];
  for (const r of rows.slice(1)) {
    if (r[0]) system = r[0];
    if (system.startsWith('Trigonal (rhombohedral axes)')) continue;
    const axis = /unique (b|c)/.exec(system)?.[1] as 'b' | 'c' | undefined;
    out.push(axis ? { short: r[1], uniqueAxis: axis } : { short: r[1] });
  }
  return out;
}

describe('ITC settings fixture against print', () => {
  it('has exactly the 32 keys', () => {
    expect(Object.keys(ITC_SETTINGS).sort()).toEqual([...POINT_GROUP_KEYS].sort());
  });

  it('every row sourced to Table 3.2.2.2 is printed there, and every printed class is in the fixture', () => {
    // Only the monoclinic rows of the print name an axis (the fixture also names the axis of mm2).
    const monoclinic = new Set(['2', 'm', '2/m']);
    const id = (short: string, axis?: string) => `${short}|${monoclinic.has(short) ? axis : ''}`;
    const fixture = Object.values(ITC_SETTINGS).flat();
    const printed = table3222Classes().map((p) => id(p.short, p.uniqueAxis));
    for (const f of fixture) if (f.source === 'table-3.2.2.2') expect(printed).toContain(id(f.short, f.uniqueAxis));
    const all = fixture.map((f) => id(f.short, f.uniqueAxis));
    for (const p of printed) expect(all).toContain(p);
  });

  it('every row sourced to Table 2.1.1.1 is printed there', () => {
    const printed = table2111Symbols();
    for (const s of Object.values(ITC_SETTINGS).flat()) {
      if (s.source === 'vol-a-table-2.1.1.1') expect(printed).toContain(s.short);
    }
  });

  it('Table 2.1.1.1 lists the 32 keys, except that it prints D3h as -62m (open question in docs/conventions.md)', () => {
    const printed = table2111Symbols();
    expect(printed).toHaveLength(32);
    expect(printed.map((s) => (s === '-62m' ? '-6m2' : s)).sort()).toEqual([...POINT_GROUP_KEYS].sort());
  });
});

describe('ITC operations of every setting = group generated by its ITC symbol', () => {
  for (const key of POINT_GROUP_KEYS) {
    describe(key, () => {
      const expected = ITC_SETTINGS[key];
      const actual = settings(key, 'itc');
      const system = crystalSystemOf(key);

      it('settings match the fixture one to one, with the standard setting as default', () => {
        expect(actual).toHaveLength(expected.length);
        for (const e of expected) {
          const match = actual.filter((s) => s.symbol === e.short && s.uniqueAxis === e.uniqueAxis);
          expect(match).toHaveLength(1);
          expect(match[0].isDefault).toBe(e.standard);
        }
      });

      for (const e of expected) {
        const label = `${e.short}${e.uniqueAxis ? ` (axis ${e.uniqueAxis})` : ''}`;
        it(`${label}: operations = closure of the symbol along the ITA symmetry directions`, () => {
          const s = actual.find((x) => x.symbol === e.short && x.uniqueAxis === e.uniqueAxis)!;
          const ops = operations(key, { convention: 'itc', setting: s.index });
          expect(sameGroup(generate(e.short, system, e.uniqueAxis), ops)).toBe(true);
        });

        it(`${label}: the full symbol generates the same group`, () => {
          const s = actual.find((x) => x.symbol === e.short && x.uniqueAxis === e.uniqueAxis)!;
          const ops = operations(key, { convention: 'itc', setting: s.index });
          expect(sameGroup(generate(s.fullSymbol, system, e.uniqueAxis), ops)).toBe(true);
        });

        it(`${label}: findPointGroup finds this setting`, () => {
          const s = actual.find((x) => x.symbol === e.short && x.uniqueAxis === e.uniqueAxis)!;
          expect(findPointGroup(s.fullSymbol, 'itc')).toEqual({ key, setting: s.index });
        });
      }
    });
  }
});

function crystalSystemOf(key: PointGroupKey): string {
  // The crystal system decides which row of Table 2.1.3.1 the symbol positions refer to.
  const rows = tableRows(readReference('itc/vol-a-table-2.1.1.1.md'));
  let system = '';
  for (const r of rows.slice(1)) {
    if (r[2]) system = r[2].toLowerCase();
    const symbols = r[3].split(',').map((s) => s.replace(/\((L|H)\)/, '').trim());
    if (symbols.includes(key) || (key === '-6m2' && symbols.includes('-62m'))) return system;
  }
  throw new Error(`No crystal system for ${key} in Table 2.1.1.1`);
}
