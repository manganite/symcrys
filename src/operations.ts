/**
 * Point operations: a Cartesian matrix, optionally combined with time reversal, and the closure of
 * a set of generators into a group.
 */

import { IDENTITY, conjugate, matricesEqual, multiply, snap, type Mat3 } from './linalg.js';

/**
 * A point operation: an orthogonal Cartesian matrix (rotation, rotoinversion, mirror, inversion),
 * combined with time reversal if `timeReversal` is true (a primed operation).
 */
export interface Operation {
  readonly matrix: Mat3;
  readonly timeReversal: boolean;
}

/** No point group has more than 48 operations (96 with time reversal); a closure beyond this is a data error. */
const MAX_GROUP_ORDER = 200;

export const IDENTITY_OPERATION: Operation = { matrix: IDENTITY, timeReversal: false };

/** A unitary operation (no time reversal). */
export function operation(matrix: Mat3): Operation {
  return { matrix, timeReversal: false };
}

/** The product a·b: first b, then a. */
export function compose(a: Operation, b: Operation): Operation {
  return { matrix: snap(multiply(a.matrix, b.matrix)), timeReversal: a.timeReversal !== b.timeReversal };
}

export function operationsEqual(a: Operation, b: Operation): boolean {
  return a.timeReversal === b.timeReversal && matricesEqual(a.matrix, b.matrix);
}

/** The operation expressed in a frame rotated by `s` (orthogonal): s·W·sᵀ. */
export function transformOperation(op: Operation, s: Mat3): Operation {
  return { matrix: snap(conjugate(op.matrix, s)), timeReversal: op.timeReversal };
}

/**
 * The group generated by `generators`: the identity first, then the generators, then products in
 * the order they are found. The order of the result is therefore fixed by the generators.
 * Throws if the closure exceeds the order of any point group (a sign of wrong input data).
 */
export function closeGroup(generators: readonly Operation[]): Operation[] {
  const group: Operation[] = [IDENTITY_OPERATION];
  const add = (op: Operation): boolean => {
    if (group.some((g) => operationsEqual(g, op))) return false;
    if (group.length >= MAX_GROUP_ORDER)
      throw new Error('closeGroup: closure does not terminate; check the generators');
    group.push(op);
    return true;
  };
  for (const g of generators) add({ matrix: snap(g.matrix), timeReversal: g.timeReversal });
  for (let i = 0; i < group.length; i++) {
    for (let j = 0; j <= i; j++) {
      add(compose(group[i], group[j]));
      add(compose(group[j], group[i]));
    }
  }
  return group;
}
