/**
 * The point group of a list of operations, and the operations described geometrically, for any
 * list (for instance the operations left after distorting a crystal; docs/conventions.md, "Point
 * group of a list of operations"). Shared by both entry points.
 */

import { TOLERANCE_KEYS, checkOptions } from '../checks.js';
import { det, dot, trace, type Mat3, type Vec3 } from '../linalg.js';
import { closedGroup, idealOfClosure, sameWithin } from '../closure.js';
import { checkCartesianOperations, checkTimeReversal, type CartesianOperation } from '../operations.js';
import { EPSILON, MAX_POINT_GROUP_ORDER, toleranceOf, type ToleranceOptions } from '../tolerances.js';
import { axialVector, rotationAxis, type OperationKind } from './elements.js';
import {
  MAGNETIC_POINT_GROUP_KEYS,
  operationInvariants,
  operations as groupOperations,
  settings,
  type MagneticPointGroupKey,
  type OperationInvariants,
} from './pointGroups.js';

/**
 * A point group found by its symbol (`findPointGroup`) or identified from operations
 * (`pointGroupOf`): its key, and the setting if the operations are exactly those of one.
 */
export interface IdentifiedPointGroup {
  /** The key of the point group. */
  readonly key: MagneticPointGroupKey;
  /**
   * The 1-based index of the setting: always for `findPointGroup`; for `pointGroupOf` the setting
   * whose operations the group equals, in the Cartesian frame of symcrys, absent if the group is the
   * point group in another orientation.
   */
  readonly setting?: number;
}

/** An axis in the Cartesian frame only, for operations that are not tied to a lattice. */
export interface CartesianAxis {
  /** Unit vector; its first non-zero component, in the order x, y, z, is positive. */
  readonly cartesian: Vec3;
}

/** One operation of any list described geometrically (`describeOperationsOf`). */
export interface CartesianOperationDescription {
  /** What the operation is, without time reversal. */
  readonly kind: OperationKind;
  /**
   * The n of the symbol n or n̄ (n for an n-fold rotation): 1 for the identity and the inversion, 2
   * for a reflection (m = 2̄), otherwise the order of the rotation part.
   *
   * @remarks Source: ITA (2016), § 1.2.1, p. 12.
   */
  readonly n: number;
  /** Rotation axis, rotoinversion axis or the normal of the mirror plane; absent for the identity and the inversion. */
  readonly axis?: CartesianAxis;
  /**
   * For n ≥ 3: `'+'` if the rotation part turns by +360°/n about `axis` (counter-clockwise seen
   * from the tip of `axis` looking towards the origin), `'-'` if by −360°/n.
   */
  readonly sense?: '+' | '-';
  /** True if the operation is combined with time reversal (a primed operation). */
  readonly timeReversal: boolean;
}

/**
 * How far the trace of a matrix with entries within `tolerance` may lie from an integer: three
 * diagonal entries, so three times the tolerance (at least that of `EPSILON`).
 */
const traceTolerance = (tolerance: number): number => 3 * Math.max(tolerance, EPSILON);

const same = sameWithin;

/**
 * The group the operations generate within the tolerance; throws the RangeError of `closedGroup` if
 * it does not close (matrices with errors too large for the tolerance, or a rotation by an angle
 * that is not 360°/n).
 */
const close = (ops: readonly CartesianOperation[], tolerance: number): CartesianOperation[] =>
  closedGroup(ops, tolerance);

/**
 * How many operations of each kind a group has: determinant, trace and time reversal of each. For
 * the 122 point groups these counts are all different (a test checks it), and since the 122 are
 * all point groups up to orientation, the counts identify the point group of any finite group of
 * crystallographic operations.
 */
const signature = (ops: readonly CartesianOperation[], tolerance = EPSILON): string =>
  ops
    .map((op) => {
      const t = trace(op.cartesian);
      const rounded = Math.round(t);
      if (Math.abs(t - rounded) > traceTolerance(tolerance)) return 'x'; // not a crystallographic operation
      return `${Math.round(det(op.cartesian))}:${rounded}${op.timeReversal ? "'" : ''}`;
    })
    .sort()
    .join(' ');

let bySignature: Map<string, MagneticPointGroupKey> | undefined;

/** The counts of a group from the invariants of its operations, written as `signature` writes them. */
const signatureOfInvariants = (invariants: readonly OperationInvariants[]): string =>
  invariants
    .map((k) => `${k.det}:${k.trace}${k.timeReversal ? "'" : ''}`)
    .sort()
    .join(' ');

function keyOfSignature(s: string): MagneticPointGroupKey | undefined {
  if (!bySignature) {
    bySignature = new Map();
    for (const key of MAGNETIC_POINT_GROUP_KEYS) bySignature.set(signatureOfInvariants(operationInvariants(key)), key);
  }
  return bySignature.get(s);
}

/**
 * The point group generated by a list of Cartesian operations, for instance those left after
 * distorting a crystal: its key, and the setting whose operations it equals in the frame of symcrys
 * (absent if the group is the point group in another orientation). The list is closed into a group
 * first, two matrices being equal when no entry differs by `tolerance` (default `EPSILON`) or more,
 * and made exact, as `tensorFormOf` makes it, so that the group identified is exact.
 * Time reversal counts: a list with time reversal gives a magnetic point group. Returns undefined
 * if the operations generate a finite group that is not a crystallographic point group (an
 * operation of order 5, a group larger than 96). Throws a RangeError for an operation without an
 * orthogonal Cartesian matrix (`cartesian`; within `tolerance`, at least `EPSILON`), for an
 * operation that does not say whether it is combined with time reversal, and if the operations do
 * not close into a finite group within the tolerance or not into an exact group near them, the
 * error of `tensorFormOf` for the same input (matrices with errors too large for it, which give
 * more than 200 elements or near copies
 * of one operation, or a rotation by an angle that is not 360°/n).
 * The classes `1` and `-1` have one setting and no orientation, so they always have
 * setting 1.
 */
export function pointGroupOf(
  operations: readonly CartesianOperation[],
  options?: ToleranceOptions,
): IdentifiedPointGroup | undefined {
  checkOptions(options, TOLERANCE_KEYS, 'pointGroupOf');
  const tolerance = toleranceOf(options, 'operations');
  checkCartesianOperations(operations, tolerance);
  checkTimeReversal(operations);
  // The exact group near the operations (idealGroup): its traces are exact, so the counts of the
  // signature cannot be shifted by the errors of the input, and a list that does not settle into
  // a group of orthogonal matrices is refused, as tensorFormOf refuses it.
  const closed = close(operations, tolerance);
  const group =
    closed.length > MAX_POINT_GROUP_ORDER ? closed : idealOfClosure(operations, closed, tolerance).operations;
  const key = group.length > MAX_POINT_GROUP_ORDER ? undefined : keyOfSignature(signature(group));
  if (!key) return undefined;
  // The operations passed in generate the group; if each is an operation of a setting of the same
  // order, the group is that setting. Products are not compared, since their errors add up.
  const setting = settings(key).find((s) => {
    const ops = groupOperations(key, { setting: s.index });
    return ops.length === group.length && operations.every((g) => ops.some((op) => same(g, op, tolerance)));
  });
  return Object.freeze(setting ? { key, setting: setting.index } : { key });
}

/**
 * The key of a complete point group, given as all its Cartesian operations without time reversal
 * (internal: the eigensymmetry of a crystal form), without the search for its setting.
 */
export function keyOfCompleteGroup(group: readonly CartesianOperation[]): MagneticPointGroupKey | undefined {
  return keyOfSignature(signature(group, EPSILON));
}

/**
 * The axis signed so that its first non-zero component, in the order x, y, z, is positive; a
 * component smaller than the tolerance counts as zero.
 */
function signed(v: Vec3, tolerance: number): { axis: Vec3; flip: boolean } {
  const first = v.find((x) => Math.abs(x) >= Math.max(tolerance, EPSILON)) ?? 0;
  return first < 0 ? { axis: [-v[0] + 0, -v[1] + 0, -v[2] + 0], flip: true } : { axis: v, flip: false };
}

function describe(op: CartesianOperation, i: number, tolerance: number): CartesianOperationDescription {
  const notCrystallographic = `Operation ${i} is not a crystallographic point operation`;
  // The trace of the rotation part is an integer exactly for the angles 360°/n, n = 1, 2, 3, 4, 6.
  const t = det(op.cartesian) > 0 ? trace(op.cartesian) : -trace(op.cartesian);
  if (Math.abs(t - Math.round(t)) > traceTolerance(tolerance)) throw new RangeError(notCrystallographic);
  // The order from the trace of the rotation part, 1 + 2 cos(360°/n): 3, −1, 0, 1, 2 for n = 1, 2, 3, 4, 6.
  const n = ({ 3: 1, [-1]: 2, 0: 3, 1: 4, 2: 6 } as Record<number, number>)[Math.round(t)];
  if (n === undefined) throw new RangeError(notCrystallographic);
  const r = (det(op.cartesian) > 0 ? op.cartesian : op.cartesian.map((row) => row.map((v) => -v))) as Mat3;
  const proper = det(op.cartesian) > 0;
  const timeReversal = op.timeReversal;
  if (n === 1) {
    checkIdeal(r, IDENTITY_MATRIX, i, tolerance);
    return Object.freeze({ kind: proper ? 'identity' : 'inversion', n: 1, timeReversal });
  }
  const { axis } = signed(rotationAxis(r, n), tolerance);
  const frozenAxis = Object.freeze({ cartesian: Object.freeze(axis) as unknown as Vec3 });
  const kind: OperationKind = proper ? 'rotation' : n === 2 ? 'reflection' : 'rotoinversion';
  const sense = n === 2 || dot(axialVector(r), axis) > 0 ? '+' : '-';
  checkIdeal(r, rotation(axis, (sense === '+' ? 2 : -2) * (Math.PI / n)), i, tolerance);
  if (n === 2) return Object.freeze({ kind, n: 2, axis: frozenAxis, timeReversal });
  return Object.freeze({ kind, n, axis: frozenAxis, sense, timeReversal });
}

const IDENTITY_MATRIX: Mat3 = [
  [1, 0, 0],
  [0, 1, 0],
  [0, 0, 1],
];

/** The rotation by `angle` (radians, right-handed) about the axis `a` (Rodrigues' formula). */
function rotation(a: Vec3, angle: number): Mat3 {
  const norm = Math.hypot(a[0], a[1], a[2]);
  const [x, y, z] = [a[0] / norm, a[1] / norm, a[2] / norm];
  const c = Math.cos(angle);
  const s = Math.sin(angle);
  const k = 1 - c;
  return [
    [c + x * x * k, x * y * k - z * s, x * z * k + y * s],
    [y * x * k + z * s, c + y * y * k, y * z * k - x * s],
    [z * x * k - y * s, z * y * k + x * s, c + z * z * k],
  ];
}

/**
 * Throws unless the rotation part of an operation equals, entry by entry within three times the
 * tolerance (as the trace test), the rotation its description names (kind, n, axis, sense): the
 * trace alone changes only to second order with the angle near 0° and 180°, so a matrix far from
 * any crystallographic operation can have an integer trace within the tolerance. The axis of the
 * description is estimated from the matrix and carries its errors, so the rebuilt operation can lie
 * up to about 2.3 times farther from the matrix than the nearest operation does; the factor 3 keeps
 * a matrix within the tolerance of an operation from being refused.
 */
function checkIdeal(r: Mat3, ideal: Mat3, i: number, tolerance: number): void {
  const deviation = Math.max(...r.flatMap((row, a) => row.map((v, b) => Math.abs(v - ideal[a][b]))));
  const bound = traceTolerance(tolerance);
  if (!(deviation < bound)) {
    throw new RangeError(
      `Operation ${i} is not a crystallographic point operation within the tolerance ${tolerance} (at least ` +
        `EPSILON): it differs from the operation it reads as by ${deviation.toPrecision(2)} in an entry, more ` +
        `than three times the tolerance`,
    );
  }
}

/**
 * Each operation of a list described geometrically, in the order of the list: kind, n, the
 * Cartesian axis (rotation or rotoinversion axis, mirror normal) with its first non-zero component,
 * in the order x, y, z, positive, and for n ≥ 3 the sense about that axis. The axes are not named
 * by lattice directions, since the list need not belong to a setting; for a point group given by its
 * key, `describeOperations` names them. Throws a RangeError for an operation without an orthogonal Cartesian matrix (`cartesian`) or
 * not a crystallographic operation (one whose matrix differs by more than three times the
 * tolerance from the operation its description names, a rotation by 360°/n, n = 1, 2, 3, 4, 6,
 * about its axis, or its product with the inversion), within `tolerance` (default `EPSILON`, as for
 * `pointGroupOf`), and for an operation that
 * does not say whether it is combined with time reversal.
 */
export function describeOperationsOf(
  operations: readonly CartesianOperation[],
  options?: ToleranceOptions,
): readonly CartesianOperationDescription[] {
  checkOptions(options, TOLERANCE_KEYS, 'describeOperationsOf');
  const tolerance = toleranceOf(options, 'operations');
  checkCartesianOperations(operations, tolerance);
  checkTimeReversal(operations);
  return Object.freeze(operations.map((op, i) => describe(op, i, tolerance)));
}
