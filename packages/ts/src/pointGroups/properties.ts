/**
 * Properties that follow from operations, for a list of operations of a caller, and the holohedry
 * of a crystal system. The properties of a point group given by its key are fields of
 * `pointGroup(key)` (pointGroups.ts). Properties that are the question whether a tensor is allowed
 * (polar, piezoelectric, ferroaxial, ferromagnetic, …) are named tensor properties
 * (tensors/tensorProperties.ts).
 */

import type { CrystalSystem } from '../lattice.js';
import { INVERSION, det, matricesEqual } from '../linalg.js';
import { checkCartesianOperations, checkTimeReversal, closeGroup, type CartesianOperation } from '../operations.js';
import type { PointGroupKey } from './keys.js';

/**
 * What every function for a list of operations asks of the list: Cartesian (orthogonal) matrices,
 * and of every operation whether it is combined with time reversal, as `tensorFormOf` does.
 */
function check(operations: readonly CartesianOperation[]): void {
  checkCartesianOperations(operations);
  checkTimeReversal(operations);
}

/**
 * True if the group generated by `operations` contains the inversion, not combined with time
 * reversal: e.g. for the operations of a distorted crystal. A list that is not closed is closed
 * first. For a point group given by its key, read `pointGroup(key).centrosymmetric`. Throws a
 * RangeError for an operation without an orthogonal Cartesian matrix (`cartesian`) and for an operation that does not say whether it
 * is combined with time reversal.
 */
export function isCentrosymmetricOf(operations: readonly CartesianOperation[]): boolean {
  check(operations);
  return closeGroup(operations).some((op) => !op.timeReversal && matricesEqual(op.cartesian, INVERSION));
}

/**
 * True if the group generated by `operations` is enantiomorphic: proper rotations only, with or
 * without time reversal (ITA § 3.2.2.1.3; products of proper rotations are proper, so the list need
 * not be closed). For a point group given by its key, read `pointGroup(key).enantiomorphic`. Throws a RangeError for an operation without an orthogonal Cartesian matrix (`cartesian`) and for an operation that does not say whether it is combined with time
 * reversal.
 */
export function isEnantiomorphicOf(operations: readonly CartesianOperation[]): boolean {
  check(operations);
  return operations.every((op) => det(op.cartesian) > 0);
}

const HOLOHEDRY: Readonly<Record<CrystalSystem, PointGroupKey>> = Object.freeze({
  triclinic: '-1',
  monoclinic: '2/m',
  orthorhombic: 'mmm',
  tetragonal: '4/mmm',
  trigonal: '-3m',
  hexagonal: '6/mmm',
  cubic: 'm-3m',
});

/**
 * The holohedry of a crystal system: the crystal class that is the point symmetry of a lattice of
 * the system (ITA Table 2.1.1.1, the Laue groups in full boxes). For the trigonal system it is
 * `-3m`, the symmetry of the rhombohedral lattice. The trigonal classes also occur with the
 * hexagonal lattice, whose symmetry is `6/mmm`: the holohedry of the crystal family is
 * `holohedry(crystalFamily(system))`, which is what the lattice basis of this library
 * (`latticeBasis`, hexagonal axes for both systems) has.
 */
export function holohedry(system: CrystalSystem): PointGroupKey {
  if (!Object.hasOwn(HOLOHEDRY, system)) throw new RangeError(`Unknown crystal system: ${JSON.stringify(system)}`);
  return HOLOHEDRY[system];
}
