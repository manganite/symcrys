/**
 * Properties of a point group that follow from its operations. They do not depend on the setting
 * or the convention. For a magnetic point group they are defined in docs/conventions.md,
 * "Properties". Properties that are the question whether a tensor is allowed (piezoelectric,
 * ferromagnetic, …) are named tensor properties (tensors/tensorProperties.ts).
 */

import { INVERSION, det, matricesEqual } from '../linalg.js';
import { EPSILON } from '../tolerances.js';
import { compose, operation, operationsEqual, type Operation } from '../operations.js';
import { POINT_GROUP_KEYS, type PointGroupKey } from './data.js';
import type { MagneticPointGroupKey } from './magneticData.js';
import { crystalClassOf, operations } from './pointGroups.js';

/** Operations in setting 1, the frame all stored data share. */
const stored = (key: MagneticPointGroupKey): readonly Operation[] => operations(key, { setting: 1 });

/** Contains the inversion, not combined with time reversal. */
export function isCentrosymmetric(key: MagneticPointGroupKey): boolean {
  return stored(key).some((op) => !op.timeReversal && matricesEqual(op.matrix, INVERSION));
}

/**
 * Polar (pyroelectric class): some direction is left unchanged by every operation, i.e. the group
 * average of the matrices, which projects onto the invariant vectors, is not zero. Time reversal
 * does not change a polar vector, so a magnetic group is polar if its crystal class is.
 */
export function isPolar(key: MagneticPointGroupKey): boolean {
  const ops = stored(key);
  for (let i = 0; i < 3; i++) {
    for (let j = 0; j < 3; j++) {
      let sum = 0;
      for (const op of ops) sum += op.matrix[i][j];
      if (Math.abs(sum / ops.length) > EPSILON) return true;
    }
  }
  return false;
}

/** Chiral (enantiomorphic class): proper rotations only, with or without time reversal. */
export function isChiral(key: MagneticPointGroupKey): boolean {
  return stored(key).every((op) => det(op.matrix) > 0);
}

function sameSet(a: readonly Operation[], b: readonly Operation[]): boolean {
  return a.length === b.length && a.every((x) => b.some((y) => operationsEqual(x, y)));
}

const laueCache = new Map<PointGroupKey, PointGroupKey>();

/**
 * The Laue class: the centrosymmetric crystal class generated by the crystal class of the group
 * and the inversion.
 */
export function laueClass(key: MagneticPointGroupKey): PointGroupKey {
  key = crystalClassOf(key);
  const cached = laueCache.get(key);
  if (cached) return cached;
  const ops = stored(key);
  const withInversion = [...ops];
  for (const op of ops) {
    const product = compose(operation(INVERSION), op);
    if (!withInversion.some((x) => operationsEqual(x, product))) withInversion.push(product);
  }
  const laue = POINT_GROUP_KEYS.find((k) => isCentrosymmetric(k) && sameSet(withInversion, stored(k)));
  if (!laue) throw new Error(`laueClass: no centrosymmetric class matches ${key}`);
  laueCache.set(key, laue);
  return laue;
}
