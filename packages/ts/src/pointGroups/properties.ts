/**
 * Properties that follow from operations, for a list of operations of a caller, and the holohedry
 * of a lattice system. The properties of a point group given by its key are fields of
 * `pointGroup(key)` (pointGroups.ts). Properties that are the question whether a tensor is allowed
 * (polar, piezoelectric, ferroaxial, ferromagnetic, …) are named tensor properties
 * (tensors/tensorProperties.ts).
 */

import { checkOptions, shown, TOLERANCE_KEYS } from '../checks.js';
import type { LatticeSystem } from '../lattice.js';
import { INVERSION, det } from '../linalg.js';
import { checkCartesianOperations, checkTimeReversal, type CartesianOperation } from '../operations.js';
import { closedGroup, sameWithin } from '../closure.js';
import { toleranceOf, type ToleranceOptions } from '../tolerances.js';
import type { PointGroupKey } from './keys.js';

/**
 * True if the group generated by `operations` contains the inversion, not combined with time
 * reversal: e.g. for the operations of a distorted crystal. The list is closed into a group within
 * the tolerance first, as `tensorFormOf` closes it, and the inversion is sought within the
 * tolerance. For a point group given by its key, read `pointGroup(key).centrosymmetric`. Throws a
 * RangeError as `tensorFormOf`.
 */
export function isCentrosymmetricOf(operations: readonly CartesianOperation[], options?: ToleranceOptions): boolean {
  checkOptions(options, TOLERANCE_KEYS, 'isCentrosymmetricOf');
  const tolerance = toleranceOf(options, 'operations');
  checkCartesianOperations(operations, tolerance);
  checkTimeReversal(operations);
  const inversion: CartesianOperation = { cartesian: INVERSION, timeReversal: false };
  return closedGroup(operations, tolerance).some((op) => sameWithin(op, inversion, tolerance));
}

/**
 * True if the group generated by `operations` is enantiomorphic: proper rotations only, with or
 * without time reversal (products of proper rotations are proper, so the list need not be closed).
 * For a point group given by its key, read `pointGroup(key).enantiomorphic`. Throws a RangeError
 * for an operation without an orthogonal Cartesian matrix (`cartesian`; within the tolerance) and
 * for an operation that does not say whether it is combined with time reversal.
 *
 * @remarks Source: ITA (2016), § 3.2.2.1.3, p. 738.
 */
export function isEnantiomorphicOf(operations: readonly CartesianOperation[], options?: ToleranceOptions): boolean {
  checkOptions(options, TOLERANCE_KEYS, 'isEnantiomorphicOf');
  checkCartesianOperations(operations, toleranceOf(options, 'operations'));
  checkTimeReversal(operations);
  return operations.every((op) => det(op.cartesian) > 0);
}

const HOLOHEDRY: Readonly<Record<LatticeSystem, PointGroupKey>> = Object.freeze({
  triclinic: '-1',
  monoclinic: '2/m',
  orthorhombic: 'mmm',
  tetragonal: '4/mmm',
  hexagonal: '6/mmm',
  rhombohedral: '-3m',
  cubic: 'm-3m',
});

/**
 * The holohedry of a lattice system, the point symmetry of its lattices, e.g. `6/mmm` for the
 * hexagonal and `-3m` for the rhombohedral lattice system. A trigonal crystal belongs to either
 * lattice system, so `latticeSystems(key)` gives two for a trigonal class. Throws a RangeError for
 * anything that is not one of the seven lattice systems, a crystal system `'trigonal'` included.
 *
 * @remarks Source: ITA (2016), Table 1.3.4.1, p. 39.
 */
export function holohedry(latticeSystem: LatticeSystem): PointGroupKey {
  if (!Object.hasOwn(HOLOHEDRY, latticeSystem)) {
    const hint =
      latticeSystem === ('trigonal' as unknown)
        ? "; a trigonal crystal has the lattice system 'hexagonal' or 'rhombohedral' (latticeSystems)"
        : '';
    throw new RangeError(`Unknown lattice system: ${shown(latticeSystem)}${hint}`);
  }
  return HOLOHEDRY[latticeSystem];
}
