/**
 * Type of a magnetic point group. `'I'`: a crystallographic point group, no operation with time
 * reversal. `'II'`: a grey group, every operation of a crystal class with and without time
 * reversal. `'III'`: a black-and-white group, half of the operations of a crystal class combined
 * with time reversal. ITC Vol. D numbers these types differently (docs/conventions.md, "Types").
 */
export type PointGroupType = 'I' | 'II' | 'III';

/**
 * A point group with the properties that are fixed by its operations. None of them depends on the
 * setting (docs/conventions.md, "Properties").
 */
export interface PointGroup<K extends MagneticPointGroupKey = PointGroupKey> {
  /** The key (docs/conventions.md, "Keys"). */
  readonly key: K;
  /** `'I'` crystal class (white group), `'II'` grey group, `'III'` black-and-white group (docs/conventions.md, "Types"). */
  readonly type: PointGroupType;
  /**
   * The crystal class of the group: the group itself for a class, otherwise the class it becomes
   * when time reversal is dropped from every operation.
   */
  readonly crystalClass: PointGroupKey;
  /** The crystal system of the crystal class. */
  readonly crystalSystem: CrystalSystem;
  /** Number of operations. */
  readonly order: number;
  /** Contains the inversion, not combined with time reversal. */
  readonly centrosymmetric: boolean;
  /**
   * Polar (pyroelectric class): some direction is left unchanged by every operation. Time reversal
   * does not change a polar vector, so a magnetic group is polar if its crystal class is.
   */
  readonly polar: boolean;
  /**
   * Enantiomorphic: proper rotations only, with or without time reversal. ITA § 3.2.2.1.3 (p. 738):
   * "All these terms [enantiomorphism, enantiomerism, chirality, dissymmetry] refer to the same
   * symmetry restriction, the absence of improper rotations (rotoinversions, rotoreflections)".
   */
  readonly enantiomorphic: boolean;
  /** The Laue class: the centrosymmetric crystal class generated by the crystal class and the inversion. */
  readonly laueClass: PointGroupKey;
}

/** A setting of a point group: an orientation of its symmetry directions in the Cartesian frame (docs/conventions.md, "Settings"). */
export interface Setting {
  /** 1-based. */
  readonly index: number;
  /** Short symbol of the setting. */
  readonly symbol: string;
  /** Full symbol, symmetry directions separated by single spaces. */
  readonly fullSymbol: string;
  /** Monoclinic settings only: the unique axis. */
  readonly uniqueAxis?: 'a' | 'b' | 'c';
  /** Trigonal settings only: the axes of the conventional basis, `'hexagonal'` or `'rhombohedral'`. */
  readonly axes?: 'hexagonal' | 'rhombohedral';
  /** True for the ITC default setting. */
  readonly isDefault: boolean;
}

/**
 * The criteria of ITA's headlines (Table 3.2.3.2) that choose among the settings a symbol names:
 * the options of `findPointGroup`, and with `setting` those of every function of a group in a
 * setting.
 */
export interface AxesOptions {
  /**
   * The axes, as ITA's headlines name them: `'rhombohedral'` chooses the setting with rhombohedral
   * axes of a trigonal group, `'hexagonal'` one with hexagonal axes, which every group of the
   * hexagonal family has. A RangeError for another family.
   */
  readonly axes?: 'hexagonal' | 'rhombohedral';
  /**
   * The unique axis of a monoclinic group, as ITA's headlines name it (`'b'`, the standard, `'c'`,
   * `'a'`). A RangeError for another system.
   */
  readonly uniqueAxis?: 'a' | 'b' | 'c';
}

/** Which setting: by index or symbol, and by the criteria of ITA's headlines. */
export interface SettingOptions extends AxesOptions {
  /**
   * The setting: its 1-based index, or a symbol, read as `findPointGroup` reads it (spaces ignored:
   * `'312'`, `'3 1 2'`, `'1 1 2'`). A symbol that several settings share (the key `'32'`, `'2'` for
   * unique axis b, c and a) gives the standard (ITC default) setting, unless `axes` or `uniqueAxis`
   * chooses another. Default: the ITC default setting.
   */
  readonly setting?: number | string;
}

/**
 * The second argument of `findPointGroup`: the criteria, checked. A string is the convention that
 * up to 0.10 came here (`findPointGroup(hm, 'birss')`), a RangeError that names the change.
 */
function criteriaArgument(arg: unknown): AxesOptions | undefined {
  if (arg === undefined) return undefined;
  if (typeof arg === 'string') rejectConventionArgument(2);
  if (typeof arg !== 'object' || arg === null) {
    throw new RangeError(`findPointGroup takes the options { axes, uniqueAxis }, not ${JSON.stringify(arg)}`);
  }
  rejectConvention(arg);
  const unknown = Object.keys(arg).filter((k) => k !== 'axes' && k !== 'uniqueAxis');
  if (unknown.length > 0) {
    throw new RangeError(`findPointGroup takes the options axes and uniqueAxis, not ${unknown.join(', ')}`);
  }
  // The values are checked here, before a group is found, so that a wrong value is an error also
  // for a symbol that names no group.
  const { axes, uniqueAxis } = arg as AxesOptions;
  if (axes !== undefined && axes !== 'hexagonal' && axes !== 'rhombohedral') {
    throw new RangeError(`axes must be 'hexagonal' or 'rhombohedral', not ${JSON.stringify(axes)}`);
  }
  if (uniqueAxis !== undefined && uniqueAxis !== 'a' && uniqueAxis !== 'b' && uniqueAxis !== 'c') {
    throw new RangeError(`uniqueAxis must be 'a', 'b' or 'c', not ${JSON.stringify(uniqueAxis)}`);
  }
  return arg as AxesOptions;
}

/** Setting and form of a symbol. */
export interface SymbolOptions extends SettingOptions {
  /**
   * `'short'` (default): short symbol of the setting, e.g. `321` for class `32` (ITA Table
   * 3.2.3.2); in the magnetic API the default setting of a grey or black-and-white group has its
   * key as short symbol (`32'` as ITC Vol. D Table 1.5.2.3 prints it; `321'`, the class key and `1'`).
   * `'full'`: full symbol, positions separated by spaces, e.g. `-3 2/m 1`.
   * `'schoenflies'`: Schoenflies symbol, subscripts written inline (`C3v`, `D2d`, `Oh`); `C3i` for
   * the class -3 in the crystallographic API (ITA), `S6` in the magnetic API (ITC Vol. D: `S6(C3)`,
   * `D3d(S6)`).
   */
  readonly form?: 'short' | 'full' | 'schoenflies';
}

/**
 * What the functions below need to know about a group, of any type. For a crystal class it is its
 * stored data; for a magnetic group it is put together from the data of its class.
 */
interface GroupData {
  readonly key: MagneticPointGroupKey;
  readonly type: PointGroupType;
  /** The crystal class: the group itself (type I), or the class it becomes without time reversal. */
  readonly crystalClass: GroupData;
  readonly crystalSystem: CrystalSystem;
  readonly schoenflies: string;
  /** The ITC default setting (itcData.ts, itcMagneticData.ts). */
  readonly itcDefault: number;
  /** The number of settings. */
  readonly settingCount: number;
}

/** The ITC default setting of a class, from the ITC class data (itcData.ts). */
function itcDefaultOf(key: PointGroupKey): number {
  return itcClass(key).settings.find((s) => s.isDefault)!.index;
}

// Built from the ITC data, in their order (that of POINT_GROUP_KEYS and
// BLACK_WHITE_POINT_GROUP_KEYS).
const BY_KEY = new Map<string, GroupData>();
for (const c of ITC_CLASSES) {
  const self: GroupData = {
    key: c.key,
    type: 'I',
    get crystalClass() {
      return self;
    },
    crystalSystem: c.crystalSystem,
    schoenflies: c.schoenflies,
    itcDefault: itcDefaultOf(c.key),
    settingCount: c.settings.length,
  };
  BY_KEY.set(c.key, self);
}
// Grey groups: the class and time reversal (ITC Vol. D, eq. (1.5.2.1)).
for (const c of ITC_CLASSES) {
  const crystalClass = BY_KEY.get(c.key)!;
  const key: MagneticPointGroupKey = `${c.key}1'`;
  BY_KEY.set(key, {
    key,
    type: 'II',
    crystalClass,
    crystalSystem: c.crystalSystem,
    schoenflies: greySchoenflies(c.schoenflies),
    itcDefault: crystalClass.itcDefault,
    settingCount: crystalClass.settingCount,
  });
}
for (const g of ITC_BLACK_WHITE) {
  const crystalClass = BY_KEY.get(g.crystalClass)!;
  BY_KEY.set(g.key, {
    key: g.key,
    type: 'III',
    crystalClass,
    crystalSystem: crystalClass.crystalSystem,
    schoenflies: g.schoenflies,
    itcDefault: g.settings.find((s) => s.isDefault)!.index,
    settingCount: g.settings.length,
  });
}

/** True if `key` is the key of one of the 32 crystal classes. */
export function isPointGroupKey(key: string): key is PointGroupKey {
  return BY_KEY.get(key)?.type === 'I';
}

/** True if `key` is the key of one of the 122 magnetic point groups (the 32 crystal classes included). */
export function isMagneticPointGroupKey(key: string): key is MagneticPointGroupKey {
  return BY_KEY.has(key);
}

function data(key: string): GroupData {
  const d = BY_KEY.get(key);
  if (!d) throw new RangeError(`Unknown point group key: ${JSON.stringify(key)}`);
  return d;
}

/**
 * Throws for the option `convention`, removed in 0.11.0 with the Birss convention, so that a caller
 * that still asks for Birss's presentation is not answered in ITC's without notice.
 */
function rejectConvention(options: object | undefined): void {
  if (options !== undefined && options !== null && 'convention' in options) {
    throw new RangeError(
      'The option convention was removed in symcrys 0.11.0: symcrys follows ITC only (CHANGELOG.md, 0.11.0)',
    );
  }
}

/**
 * Throws for a second argument of `settings` or `findPointGroup`, which took a convention up to
 * 0.10 (`settings('32', 'birss')`): TypeScript refuses it, plain JavaScript would ignore it and
 * answer for the ITC frame. Internal.
 */
export function rejectConventionArgument(argumentCount: number): void {
  if (argumentCount > 1) {
    throw new RangeError(
      'The convention argument was removed in symcrys 0.11.0: symcrys follows ITC only (CHANGELOG.md, 0.11.0)',
    );
  }
}

/** The settings a symbol names, spaces ignored: by its key, its short or full symbol, or Birss's cubic form. */
function settingsNamed(d: GroupData, text: string): number[] {
  const compactText = compact(text);
  const target = birssCubic(compactText) === d.key ? d.key : compactText;
  return allSettings(d).filter((i) => {
    if (target === d.key && i === d.itcDefault) return true;
    const s = settingSymbols(d, i);
    return compact(s.short) === target || compact(derivedSymbols(d, i).short) === target || compact(s.full) === target;
  });
}

const allSettings = (d: GroupData): number[] => Array.from({ length: d.settingCount }, (_, i) => i + 1);

/** The settings of `d`, listed for an error message. */
function listSettings(d: GroupData, indices: readonly number[]): string {
  return indices
    .map((i) => {
      const axes = settingAxes(d, i);
      const unique = settingUniqueAxis(d, i);
      const note = axes ? `, ${axes} axes` : unique ? `, unique axis ${unique}` : '';
      return `${i}: ${settingSymbols(d, i).short} (${settingSymbols(d, i).full}${note})`;
    })
    .join(', ');
}

/** `axes` and `uniqueAxis` of the options, checked against the family of the group. */
function criteriaOf(
  d: GroupData,
  options: SettingOptions | undefined,
): { readonly axes?: 'hexagonal' | 'rhombohedral'; readonly uniqueAxis?: 'a' | 'b' | 'c' } {
  const axes = options?.axes;
  const uniqueAxis = options?.uniqueAxis;
  if (axes !== undefined) {
    if (axes !== 'hexagonal' && axes !== 'rhombohedral') {
      throw new RangeError(`axes must be 'hexagonal' or 'rhombohedral', not ${JSON.stringify(axes)}`);
    }
    if (crystalFamily(d.crystalSystem) !== 'hexagonal') {
      throw new RangeError(
        `Point group ${d.key} (${d.crystalSystem}): axes applies to the trigonal and hexagonal groups`,
      );
    }
  }
  if (uniqueAxis !== undefined) {
    if (uniqueAxis !== 'a' && uniqueAxis !== 'b' && uniqueAxis !== 'c') {
      throw new RangeError(`uniqueAxis must be 'a', 'b' or 'c', not ${JSON.stringify(uniqueAxis)}`);
    }
    if (d.crystalSystem !== 'monoclinic') {
      throw new RangeError(`Point group ${d.key} (${d.crystalSystem}): uniqueAxis applies to the monoclinic groups`);
    }
  }
  return { ...(axes ? { axes } : {}), ...(uniqueAxis ? { uniqueAxis } : {}) };
}

/** Whether setting `i` meets the criteria (`axes: 'hexagonal'` holds for every hexagonal group). */
function meets(d: GroupData, i: number, c: ReturnType<typeof criteriaOf>): boolean {
  if (c.axes && (settingAxes(d, i) ?? 'hexagonal') !== c.axes) return false;
  if (c.uniqueAxis && settingUniqueAxis(d, i) !== c.uniqueAxis) return false;
  return true;
}

/**
 * The setting among `candidates` that meets the criteria: the only one, or the standard (ITC
 * default) where it is one of several, as a name without a criterion means the standard (Thomas,
 * 2026-11-23, #96). None, or several without the standard, is a RangeError that lists them.
 */
function choose(
  d: GroupData,
  candidates: readonly number[],
  criteria: ReturnType<typeof criteriaOf>,
  what: string,
): number {
  const met = candidates.filter((i) => meets(d, i, criteria));
  if (met.length === 1) return met[0]!;
  if (met.includes(d.itcDefault)) return d.itcDefault;
  const crit = [criteria.axes && `${criteria.axes} axes`, criteria.uniqueAxis && `unique axis ${criteria.uniqueAxis}`]
    .filter(Boolean)
    .join(', ');
  const asked = what ? [what, crit].filter(Boolean).join(', ') : `with ${crit}`;
  throw new RangeError(
    met.length === 0
      ? `Point group ${d.key} has no setting ${asked} (settings ${listSettings(d, allSettings(d))})`
      : `Point group ${d.key}: ${asked} names ${met.length} settings; give the index (${listSettings(d, met)})`,
  );
}

/** The requested setting index, checked; the ITC default if none is given. */
function settingIndex(d: GroupData, options?: SettingOptions): number {
  rejectConvention(options);
  const criteria = criteriaOf(d, options);
  const requested = options?.setting;
  if (requested !== undefined && requested !== null && typeof requested !== 'number' && typeof requested !== 'string') {
    throw new RangeError(`The setting must be an index or a symbol, not ${JSON.stringify(requested)}`);
  }
  if (typeof requested === 'string') {
    const named = settingsNamed(d, requested);
    if (named.length === 0) {
      throw new RangeError(
        `Point group ${d.key} has no setting ${JSON.stringify(requested)} (settings ${listSettings(d, allSettings(d))})`,
      );
    }
    return choose(d, named, criteria, JSON.stringify(requested));
  }
  if (requested === undefined || requested === null) return choose(d, allSettings(d), criteria, '');
  const count = d.settingCount;
  if (!Number.isInteger(requested) || requested < 1 || requested > count) {
    throw new RangeError(`Point group ${d.key} has no setting ${String(requested)} (settings 1 to ${count})`);
  }
  if (!meets(d, requested, criteria)) {
    throw new RangeError(
      `Point group ${d.key}: setting ${requested} does not have the ${[criteria.axes && `${criteria.axes} axes`, criteria.uniqueAxis && `unique axis ${criteria.uniqueAxis}`].filter(Boolean).join(', ')} (settings ${listSettings(d, allSettings(d))})`,
    );
  }
  return requested;
}

/**
 * The index of the requested setting (an index or a symbol; the ITC default if none), checked.
 * Internal: for the modules that cache by setting.
 */
export function settingIndexOf(key: MagneticPointGroupKey, options?: SettingOptions): number {
  return settingIndex(data(key), options);
}

function freezeOperation(op: CartesianOperation): CartesianOperation {
  const [r0, r1, r2] = op.cartesian;
  return Object.freeze({
    cartesian: Object.freeze([Object.freeze([...r0]), Object.freeze([...r1]), Object.freeze([...r2])] as const),
    timeReversal: op.timeReversal,
  }) as CartesianOperation;
}

const operationCache = new Map<string, readonly CartesianOperation[]>();

/** The operation of `ops` with the matrix of `op`, whatever its time reversal. */
function withMatrix(ops: readonly CartesianOperation[], op: CartesianOperation): CartesianOperation {
  const found = ops.find((x) => matricesEqual(x.cartesian, op.cartesian));
  if (!found) throw new Error('Operation of the crystal class missing in the magnetic group');
  return found;
}

/**
 * The setting of the crystal class whose frame is that of setting `index` of the group: the one
 * in which the class has the operations of the group without their time reversal. For a class and
 * a grey group it is `index` itself; for a black-and-white group, the class setting named by its
 * ITC symbol without primes (itcMagneticData.ts). A black-and-white group may have its settings in
 * another order than its class, and settings its class does not tell apart (docs/conventions.md,
 * "Settings").
 */
function classSetting(d: GroupData, index: number): number {
  return d.type === 'III' ? itcBlackWhiteClassSetting(d.key as BlackWhitePointGroupKey, index) : index;
}

/** The unique axis of a monoclinic setting; undefined in other systems. */
function settingUniqueAxis(d: GroupData, index: number): 'a' | 'b' | 'c' | undefined {
  return d.type === 'III'
    ? itcBlackWhiteSetting(d.key as BlackWhitePointGroupKey, index).uniqueAxis
    : itcSetting(d.crystalClass.key as PointGroupKey, index).uniqueAxis;
}

/** The axes of a trigonal setting, `'hexagonal'` or `'rhombohedral'`; undefined in other systems. */
function settingAxes(d: GroupData, index: number): 'hexagonal' | 'rhombohedral' | undefined {
  return d.type === 'III'
    ? itcBlackWhiteSetting(d.key as BlackWhitePointGroupKey, index).axes
    : itcSetting(d.crystalClass.key as PointGroupKey, index).axes;
}

/**
 * The crystal class of a group and the setting of the class whose frame and basis the requested
 * setting of the group has. Internal: for the modules that need the basis or the symmetry
 * directions of a setting.
 */
export function classSettingOf(
  key: MagneticPointGroupKey,
  options?: SettingOptions,
): { readonly key: PointGroupKey; readonly index: number } {
  const d = data(key);
  return { key: d.crystalClass.key as PointGroupKey, index: classSetting(d, settingIndex(d, options)) };
}

const itaGeneratorCache = new Map<string, readonly CartesianOperation[]>();

/**
 * ITA's generators of a setting (see `generators`); for a class from the ITC class data. For a
 * magnetic group: ITA's generators of its class in the same frame, each with the time reversal it
 * has in the group; for a grey group followed by time reversal 1'.
 */
function settingItaGenerators(d: GroupData, index: number): readonly CartesianOperation[] {
  const cacheKey = `${d.key}#${index}`;
  let result = itaGeneratorCache.get(cacheKey);
  if (!result) {
    let gens: CartesianOperation[];
    if (d.type === 'I') {
      gens = itcCartesianGenerators(d.key as PointGroupKey, index).map((m) => operation(m));
    } else {
      const classGens = settingItaGenerators(d.crystalClass, classSetting(d, index));
      gens =
        d.type === 'II'
          ? [...classGens, TIME_REVERSAL]
          : classGens.map((g) => withMatrix(settingOperations(d, index), g));
    }
    result = Object.freeze(gens.map(freezeOperation));
    itaGeneratorCache.set(cacheKey, result);
  }
  return result;
}

/**
 * The operations of a setting in ITA's order (docs/conventions.md, "Order of the operations"). A
 * crystal class: from the ITC class data (itcData.ts), built coset by coset from ITA's generators.
 * A black-and-white group: the operations of its class in the setting its ITC symbol names, in
 * that order, each with the time reversal its symbol gives (itcMagneticData.ts). A grey group: the
 * operations of its class, then the same sequence combined with time reversal.
 */
function settingOperations(d: GroupData, index: number): readonly CartesianOperation[] {
  const cacheKey = `${d.key}#${index}`;
  let result = operationCache.get(cacheKey);
  if (!result) {
    let ordered: CartesianOperation[];
    if (d.type === 'I') {
      ordered = itcCartesianOperations(d.key as PointGroupKey, index).map((m) => operation(m));
    } else if (d.type === 'II') {
      const classOps = settingOperations(d.crystalClass, index);
      ordered = [...classOps, ...classOps.map((op) => compose(TIME_REVERSAL, op))];
    } else {
      ordered = [...itcBlackWhiteOperations(d.key as BlackWhitePointGroupKey, index)];
    }
    result = Object.freeze(ordered.map(freezeOperation));
    operationCache.set(cacheKey, result);
  }
  return result;
}

const symbolCache = new Map<string, { readonly short: string; readonly full: string }>();

/**
 * Short and full symbol of a setting as symcrys gives them (#137 B2): those of `derivedSymbols`,
 * except that the default setting of a grey or black-and-white group has its key as short symbol:
 * that of ITC Vol. D Table 1.5.2.3 for a black-and-white group (`32'`, not `32'1`), the class key
 * followed by `1'` for a grey group (`321'`, not `3211'`). A crystal class keeps
 * ITA's symbol (`321`) in both entry points.
 */
function settingSymbols(d: GroupData, index: number): { readonly short: string; readonly full: string } {
  const derived = derivedSymbols(d, index);
  return d.type !== 'I' && index === d.itcDefault ? { short: d.key, full: derived.full } : derived;
}

/**
 * Short and full symbol of a setting by the rule. A crystal class: from the ITC class data
 * (itcData.ts). A grey group: the symbols of its class followed by `1'`. A black-and-white group:
 * the symbols of its class in the same frame, with the primes of its operations
 * (magneticSymbols.ts).
 */
function derivedSymbols(d: GroupData, index: number): { readonly short: string; readonly full: string } {
  if (d.type === 'I') {
    const s = itcSetting(d.key as PointGroupKey, index);
    return Object.freeze({ short: s.short, full: s.full });
  }
  const cacheKey = `${d.key}#${index}`;
  let result = symbolCache.get(cacheKey);
  if (!result) {
    const classSymbols = derivedSymbols(d.crystalClass, classSetting(d, index));
    result = Object.freeze(
      d.type === 'II'
        ? { short: `${classSymbols.short}1'`, full: `${classSymbols.full} 1'` }
        : primedSymbols(classSymbols, d.crystalSystem, settingOperations(d, index)),
    );
    symbolCache.set(cacheKey, result);
  }
  return result;
}

// --- properties fixed by the operations (setting 1; a class and its Laue class share its frame) ----

/** Contains the inversion, not combined with time reversal. */
function hasInversion(ops: readonly CartesianOperation[]): boolean {
  return ops.some((op) => !op.timeReversal && matricesEqual(op.cartesian, INVERSION));
}

/**
 * Some direction is left unchanged by every operation: the group average of the matrices, which
 * projects onto the invariant vectors, is not zero.
 */
function hasFixedDirection(ops: readonly CartesianOperation[]): boolean {
  for (let i = 0; i < 3; i++) {
    for (let j = 0; j < 3; j++) {
      let sum = 0;
      for (const op of ops) sum += op.cartesian[i][j];
      if (Math.abs(sum / ops.length) > EPSILON) return true;
    }
  }
  return false;
}

const laueCache = new Map<string, PointGroupKey>();

/** The centrosymmetric crystal class generated by a crystal class and the inversion. */
function laueClassOf(crystalClass: GroupData): PointGroupKey {
  const cached = laueCache.get(crystalClass.key);
  if (cached) return cached;
  const ops = settingOperations(crystalClass, 1);
  const inversion: CartesianOperation = { cartesian: INVERSION, timeReversal: false };
  const withInversion = [...ops];
  for (const op of ops) {
    const product = compose(inversion, op);
    if (!withInversion.some((x) => operationsEqual(x, product))) withInversion.push(product);
  }
  const sameSet = (other: readonly CartesianOperation[]): boolean =>
    other.length === withInversion.length && other.every((x) => withInversion.some((y) => operationsEqual(x, y)));
  const laue = POINT_GROUP_KEYS.find((key) => sameSet(settingOperations(data(key), 1)));
  if (!laue) throw new Error(`No centrosymmetric class matches ${crystalClass.key} with the inversion`);
  laueCache.set(crystalClass.key, laue);
  return laue;
}

const groupCache = new Map<string, PointGroup<MagneticPointGroupKey>>();

/**
 * The point group with this key: a crystal class or a magnetic point group. Throws a RangeError
 * for an unknown key.
 */
export function pointGroup<K extends MagneticPointGroupKey>(key: K): PointGroup<K> {
  const d = data(key);
  let g = groupCache.get(d.key);
  if (!g) {
    const ops = settingOperations(d, 1);
    g = Object.freeze({
      key: d.key,
      type: d.type,
      crystalClass: d.crystalClass.key as PointGroupKey,
      crystalSystem: d.crystalSystem,
      order: ops.length,
      centrosymmetric: hasInversion(ops),
      polar: hasFixedDirection(ops),
      enantiomorphic: ops.every((op) => det(op.cartesian) > 0),
      laueClass: laueClassOf(d.crystalClass),
    });
    groupCache.set(d.key, g);
  }
  return g as PointGroup<K>;
}

/** All 32 crystal classes, in the order of `POINT_GROUP_KEYS` (by crystal system, as in ITA). */
export function pointGroups(): readonly PointGroup[] {
  return POINT_GROUP_KEYS.map((key) => pointGroup(key));
}

/**
 * All 122 magnetic point groups, in the order of `POINT_GROUP_KEYS` of the magnetic API: the 32 crystal
 * classes (type I), the 32 grey groups (type II) in the same order, and the 58 black-and-white
 * groups (type III) in the order of ITC Vol. D Table 1.5.2.3.
 */
export function magneticPointGroups(): readonly PointGroup<MagneticPointGroupKey>[] {
  return MAGNETIC_POINT_GROUP_KEYS.map((key) => pointGroup(key));
}

/**
 * The key of the crystal class of a point group: the group itself for a class, otherwise the class
 * it becomes when time reversal is dropped from every operation. Internal (not exported from
 * index.ts).
 */
export function crystalClassOf(key: MagneticPointGroupKey): PointGroupKey {
  return data(key).crystalClass.key as PointGroupKey;
}

/** The settings of a point group, with their symbols and the ITC default. */
export function settings(key: MagneticPointGroupKey): readonly Setting[] {
  rejectConventionArgument(arguments.length);
  const d = data(key);
  return Array.from({ length: d.settingCount }, (_, i) => {
    const symbols = settingSymbols(d, i + 1);
    const data =
      d.type === 'III'
        ? itcBlackWhiteSetting(d.key as BlackWhitePointGroupKey, i + 1)
        : itcSetting(d.crystalClass.key as PointGroupKey, i + 1);
    return Object.freeze({
      index: i + 1,
      symbol: symbols.short,
      fullSymbol: symbols.full,
      ...(data.uniqueAxis ? { uniqueAxis: data.uniqueAxis } : {}),
      ...(data.axes ? { axes: data.axes } : {}),
      isDefault: i + 1 === d.itcDefault,
    });
  });
}

const frozenMatrix = (m: Mat3 | IntMat3): Mat3 =>
  Object.freeze(m.map((row) => Object.freeze(row.map((v) => v + 0)))) as unknown as Mat3;

/** An integer matrix from one that should be one; throws if it is not (a data error). Internal. */
export function integer(m: Mat3, what: string): Mat3 {
  const r = m.map((row) => row.map((v) => Math.round(v) + 0)) as unknown as Mat3;
  if (!m.every((row, i) => row.every((v, j) => Math.abs(v - r[i][j]) < 1e-9))) {
    throw new Error(`${what} is not an integer matrix in the lattice basis: ${JSON.stringify(m)}`);
  }
  return r;
}

/**
 * The records of the API for Cartesian operations of a setting: each with its matrix W in the
 * lattice basis of the setting. A crystal class takes W from the exact ITC class data (`exact`, in
 * the same order); a magnetic group computes W = B⁻¹·R·B in the basis B of the setting of its class
 * (itcData.ts, `itcBasis`), which is exact after rounding, since W is an integer matrix.
 */
function records(
  d: GroupData,
  index: number,
  ops: readonly CartesianOperation[],
  exact: readonly IntMat3[] | undefined,
): readonly Operation[] {
  const classKey = d.crystalClass.key as PointGroupKey;
  const b = itcBasis(classKey, classSetting(d, index));
  const bInv = inverse(b);
  return Object.freeze(
    ops.map((op, i) =>
      Object.freeze({
        matrix: frozenMatrix(
          exact ? exact[i] : integer(multiply(multiply(bInv, op.cartesian), b), `Operation ${i} of ${d.key}`),
        ),
        cartesian: op.cartesian,
        timeReversal: op.timeReversal,
      }),
    ),
  );
}

const recordCache = new Map<string, readonly Operation[]>();

/**
 * All operations of the point group in the requested setting (default: the ITC default setting),
 * in ITA's order: identity first, then as ITA numbers the general position of the crystal class; an
 * operation of a magnetic group has the number it has in the class, and a grey group lists the
 * class first, then the same sequence with time reversal (docs/conventions.md, "Order of the
 * operations"). Each operation is ITA's matrix W in the lattice basis of the setting (`matrix`) with
 * the same operation as a Cartesian matrix (`cartesian`) and its time reversal (docs/conventions.md,
 * "Operations").
 */
export function operations(key: MagneticPointGroupKey, options?: SettingOptions): readonly Operation[] {
  const d = data(key);
  const index = settingIndex(d, options);
  const cacheKey = `${d.key}#${index}`;
  let result = recordCache.get(cacheKey);
  if (!result) {
    const exact = d.type === 'I' ? itcLatticeOperations(d.key as PointGroupKey, index) : undefined;
    result = records(d, index, settingOperations(d, index), exact);
    recordCache.set(cacheKey, result);
  }
  return result;
}

/**
 * Generators of the point group in the requested setting (docs/conventions.md, "Generators"): ITA's
 * selected generators in printed order, without the identity and ITA's lattice translations, so
 * the list is empty for `1`; for the settings ITA does not print (`mm2` settings 2 and 3, monoclinic unique axis a), those of setting 1 carried
 * into their frame; for a magnetic group, those of its class with the time reversal they
 * have in the group, for a grey group followed by `1'`.
 */
export function generators(key: MagneticPointGroupKey, options?: SettingOptions): readonly Operation[] {
  const d = data(key);
  const index = settingIndex(d, options);
  const cacheKey = `${d.key}#${index}#generators`;
  let result = recordCache.get(cacheKey);
  if (!result) {
    const exact = d.type === 'I' ? itcLatticeGenerators(d.key as PointGroupKey, index) : undefined;
    result = records(d, index, settingItaGenerators(d, index), exact);
    recordCache.set(cacheKey, result);
  }
  return result;
}

/**
 * A Schoenflies symbol as ITC Vol. D writes it (#137 B3): `S6` for the class -3, where ITA writes
 * `C3i` (Table 3.2.1.2), as the crystallographic API does, and so `S6R` for its grey group. The
 * black-and-white groups store their symbols as Vol. D prints them (`S6(C3)`, `D3d(S6)`,
 * `C6h(S6)`; itcMagneticData.ts).
 */
const volDSchoenflies = (s: string): string => s.replace(/C3i/g, 'S6');

/** The Schoenflies symbol of a crystal class as ITA writes it (`C3i`). Internal: for the crystallographic API. */
export function itaSchoenflies(key: PointGroupKey): string {
  return data(key).schoenflies;
}

/**
 * A symbol of the point group in the requested setting. The default setting of a grey or
 * black-and-white group has its key as short symbol (`32'`, as ITC Vol. D Table 1.5.2.3 prints it;
 * `321'`), a crystal class ITA's symbol (`321`), and the Schoenflies symbols follow ITC Vol. D
 * (`S6`, `D3d(S6)`; docs/conventions.md, "Symbols").
 */
export function symbol(key: MagneticPointGroupKey, options?: SymbolOptions): string {
  const d = data(key);
  const form = options?.form ?? 'short';
  const s = settingSymbols(d, settingIndex(d, options));
  if (form === 'schoenflies') return volDSchoenflies(d.schoenflies);
  if (form === 'short') return s.short;
  if (form === 'full') return s.full;
  throw new RangeError(`Unknown symbol form: ${JSON.stringify(form)}`);
}

/** A point group in a given setting. */
export interface PointGroupInSetting<K extends MagneticPointGroupKey = PointGroupKey> {
  /** The key of the point group. */
  readonly key: K;
  /** The 1-based index of the setting. */
  readonly setting: number;
}

/** A symbol in the spelling of this library without spaces (notation.ts). */
const compact = compactSymbol;

function find(
  hm: string,
  classesOnly: boolean,
  options: AxesOptions | undefined,
): PointGroupInSetting<MagneticPointGroupKey> | undefined {
  if (typeof hm !== 'string') return undefined;
  const target = compact(hm);
  const candidates = [...BY_KEY.values()].filter((d) => !classesOnly || d.type === 'I');
  // The key, a short or full symbol of a setting (spaces ignored), Birss's cubic form; then a
  // Schoenflies symbol, ITA's `C3i` or ITC Vol. D's `S6` alike, which names the group and not an
  // orientation (Thomas, 2026-11-23, #96). A symbol of several groups is an error.
  let found = candidates.map((d) => ({ d, named: settingsNamed(d, hm) })).filter((m) => m.named.length > 0);
  if (found.length === 0) {
    const inVolD = volDSchoenflies(target);
    found = candidates
      .filter((d) => volDSchoenflies(d.schoenflies) === inVolD)
      .map((d) => ({ d, named: allSettings(d) }));
  }
  if (found.length > 1) {
    throw new RangeError(
      `The symbol ${JSON.stringify(hm)} names several point groups: ${found.map((m) => m.d.key).join(', ')}`,
    );
  }
  if (found.length === 0) return undefined;
  const { d, named } = found[0]!;
  // A name that several settings share gives the standard, unless axes or uniqueAxis chooses another.
  return { key: d.key, setting: choose(d, named, criteriaOf(d, options), JSON.stringify(hm)) };
}

/**
 * Birss prints the cubic groups without the overbar on the 3, which takes the prime of the mirror
 * before it (Birss Tables 3 and 6: `m3m`, `m'3` for `m-3m`, `m'-3'`): the symbol with the overbar,
 * which the caller looks up as a key (the cubic groups have one setting); undefined for any other
 * symbol.
 */
function birssCubic(compactTarget: string): string | undefined {
  const m = /^m('?)3(?!')(.*)$/.exec(compactTarget);
  return m ? `m${m[1]}-3${m[1]}${m[2]}` : undefined;
}

/**
 * Finds a crystal class by a symbol, read tolerantly.
 * It reads, spaces ignored (#96; docs/conventions.md, "Reading symbols"): the key; the short or
 * full symbol of a setting (`312`, `1 1 2`); a Schoenflies symbol, ITA's or ITC Vol. D's (`D3`,
 * `C3i`, `S6`); Birss's cubic symbols without the overbar on the 3 (`m3m`). A symbol that names
 * several settings (the key `32`, which is also the symbol of the setting with rhombohedral axes;
 * `2` for unique axis b, c and a; any Schoenflies symbol) gives the standard (ITC default) setting,
 * unless the options `axes` or `uniqueAxis` choose another, as the headlines of ITA name the
 * settings (the option `axes` set to `'rhombohedral'` for the key `32`).
 *
 * Spellings: the overbar as `-`, `−`, a combining overbar or `¯` after the digit (`m3̄m`), `bar3` (also with a backslash and braces, as in LaTeX);
 * Schoenflies subscripts also as Unicode or LaTeX subscripts (`C₃ᵥ`, `C_{3v}`). Returns undefined if nothing matches,
 * also for a value that is not a string and for the symbol of a magnetic group with time reversal
 * (`findMagneticPointGroup`); a symbol that names several groups is a RangeError that lists them.
 */
export function findPointGroup(hm: string, options?: AxesOptions): PointGroupInSetting | undefined {
  if (arguments.length > 2) rejectConventionArgument(arguments.length);
  return find(hm, true, criteriaArgument(options)) as PointGroupInSetting | undefined;
}

/**
 * Finds one of the 122 magnetic point groups (the 32 crystal classes included) by a symbol, read
 * tolerantly. A prime marks time reversal: `4'/mmm'`, `2221'`.
 * It reads, spaces ignored (#96; docs/conventions.md, "Reading symbols"): the key; the short or
 * full symbol of a setting (`312`, `1 1 2`); a Schoenflies symbol, ITA's or ITC Vol. D's (`D3`,
 * `C3i`, `S6`); Birss's cubic symbols without the overbar on the 3 (`m3m`). A symbol that names
 * several settings (the key `32`, which is also the symbol of the setting with rhombohedral axes;
 * `2` for unique axis b, c and a; any Schoenflies symbol) gives the standard (ITC default) setting,
 * unless the options `axes` or `uniqueAxis` choose another, as the headlines of ITA name the
 * settings (the option `axes` set to `'rhombohedral'` for the key `32`).
 *
 * Spellings: the overbar as `-`, `−`, a combining overbar or `¯` after the digit (`m3̄m`), `bar3` (also with a backslash and braces, as in LaTeX);
 * the prime as `'`, `′`, `ʹ` or `’`; Schoenflies subscripts also as Unicode or LaTeX subscripts (`D₃d(S₆)`, `D_{3d}`).
 * Returns undefined if nothing matches, also for a value that is not a string; a symbol that names
 * several groups is a RangeError that lists them.
 */
export function findMagneticPointGroup(
  hm: string,
  options?: AxesOptions,
): PointGroupInSetting<MagneticPointGroupKey> | undefined {
  if (arguments.length > 2) rejectConventionArgument(arguments.length);
  return find(hm, false, criteriaArgument(options));
}
