/**
 * Reading a Hermann–Mauguin symbol into a group, independently of the library (test-only code):
 * each position of the symbol names the symmetry elements along one Cartesian direction (an axis
 * `N` or `-N`, a mirror normal `m`, or both, `N/m`; `1` names none).
 */

import { I3, close, mirrorNormal, neg, rotationAbout, type RefOp } from './independentGroups.js';

/**
 * The positions of a symbol: `N`, `-N`, `N/m`, `m`, each element with a prime if it is combined
 * with time reversal (`4'/m`, `m'`); a final `1'` is time reversal itself (grey groups). Spaces are
 * ignored.
 */
export function hmTokens(hm: string): string[] {
  const compact = hm.replace(/\s+/g, '');
  const list = compact.match(/-?[1-6]'?(\/m'?)?|m'?/g) ?? [];
  if (list.join('') !== compact) throw new Error(`Unreadable symbol: ${hm}`);
  return list;
}

/** Generators of one position along the Cartesian direction u. */
function positionGenerators(token: string, u: number[]): RefOp[] {
  const mirror = /^m('?)$/.exec(token);
  if (mirror) return [{ m: mirrorNormal(u), t: mirror[1] !== '' }];
  const m = /^(-?)([1-6])('?)(?:\/m('?))?$/.exec(token);
  if (!m) throw new Error(`Unreadable position: ${token}`);
  const rotation = rotationAbout(u, 1 / Number(m[2]));
  const gens: RefOp[] = [{ m: m[1] ? neg(rotation) : rotation, t: m[3] !== '' }];
  if (m[4] !== undefined) gens.push({ m: mirrorNormal(u), t: m[4] !== '' });
  return gens;
}

/**
 * The group generated by the symbol, its positions taken along `directions` (Cartesian) in order.
 * A final `1'` beyond the positions (grey groups) adds time reversal.
 */
export function groupOfSymbol(hm: string, directions: number[][]): RefOp[] {
  const list = hmTokens(hm);
  const grey = list.length > 1 && list[list.length - 1] === "1'";
  const positions = grey ? list.slice(0, -1) : list;
  if (positions.length > directions.length) throw new Error(`${hm}: more positions than directions`);
  const gens = positions.flatMap((t, i) => (t === '1' ? [] : positionGenerators(t, directions[i])));
  if (grey) gens.push({ m: I3, t: true });
  return close(gens);
}
