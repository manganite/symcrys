/**
 * Which named tensor properties a point group allows: the property is allowed if the tensor that
 * describes it (`TENSOR_PROPERTIES`) has a non-zero form under the group. Symmetry only allows a
 * property; whether a crystal shows it is a question of the material.
 *
 * A key of type `'I'` (`'432'`) is a crystal class and, in magnetism, the white group with the same
 * operations: the symmetry of a magnetically ordered crystal in which time reversal does not occur
 * at all. For a time-odd property it is read as that group (`'432'` is magnetoelectric). A crystal
 * without magnetic order has the grey group of its class (`"4321'"`), which allows no time-odd
 * property; for the time-even properties the two agree (docs/conventions.md, "Types").
 */

import type { Operation } from '../operations.js';
import type { MagneticPointGroupKey } from '../pointGroups/pointGroups.js';
import { TENSOR_PROPERTY_NAMES, specOf, type TensorPropertyName } from './propertyTable.js';
import { tensorForm, tensorFormOf } from './tensorForm.js';

/** A name of the table; anything else, a specification included, is an error here. */
function named(name: TensorPropertyName): TensorPropertyName {
  if (typeof name !== 'string') throw new RangeError(`Unknown tensor property: ${JSON.stringify(name)}`);
  specOf(name);
  return name;
}

/**
 * True if the point group allows the named property, e.g. `allowsProperty('-6m2', 'piezoelectric')`.
 * It does not depend on setting or convention. Throws a RangeError for an unknown key or name.
 */
export function allowsProperty(key: MagneticPointGroupKey, name: TensorPropertyName): boolean {
  return tensorForm(key, named(name), { setting: 1 }).basis.length > 0;
}

/** The named properties the point group allows, in the order of `TENSOR_PROPERTIES`. */
export function allowedProperties(key: MagneticPointGroupKey): TensorPropertyName[] {
  return TENSOR_PROPERTY_NAMES.filter((name) => allowsProperty(key, name));
}

/**
 * True if the group generated by `operations` allows the named property, e.g. for the site
 * symmetry of a surface normal or the operations of a distorted crystal.
 */
export function allowsPropertyOf(operations: readonly Operation[], name: TensorPropertyName): boolean {
  return tensorFormOf(operations, named(name)).basis.length > 0;
}

/** The named properties the group generated by `operations` allows. */
export function allowedPropertiesOf(operations: readonly Operation[]): TensorPropertyName[] {
  return TENSOR_PROPERTY_NAMES.filter((name) => allowsPropertyOf(operations, name));
}
