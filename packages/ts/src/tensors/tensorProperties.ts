/**
 * Which named tensor properties a point group allows: the property is allowed if the tensor that
 * describes it (`TENSOR_PROPERTIES`) has a non-zero form under the group. Symmetry only allows a
 * property; whether a crystal shows it is a question of the material.
 *
 * These functions serve the magnetic API (`magnetic.ts`), where a key of type `'I'` (`'432'`) is the
 * white group: the symmetry of a magnetically ordered crystal in which time reversal does not occur
 * at all (`'432'` is magnetoelectric). A crystal without magnetic order has the grey group of its
 * class (`"4321'"`), which allows no time-odd property; for the time-even properties the two agree.
 * The crystallographic API (`crystalClasses.ts`) knows the time-even properties only
 * (docs/conventions.md, "Two entry points").
 */

import { checkOptions, shown, TOLERANCE_KEYS } from '../checks.js';
import type { CartesianOperation } from '../operations.js';
import type { MagneticPointGroupKey } from '../pointGroups/pointGroups.js';
import { TENSOR_PROPERTY_NAMES, specOf, type TensorPropertyName } from './propertyTable.js';
import { allowsTensor, callerGroup, checkedSpec, tensorForm } from './tensorForm.js';
import type { ToleranceOptions } from '../tolerances.js';
import type { IdealGroup } from '../closure.js';
import { deepFreeze } from '../freeze.js';

/** A name of the table; anything else, a specification included, is an error here. */
function named(name: TensorPropertyName): TensorPropertyName {
  if (typeof name !== 'string') throw new RangeError(`Unknown tensor property: ${shown(name)}`);
  specOf(name);
  return name;
}

/**
 * True if the point group allows the named property, e.g. `allowsProperty('-6m2', 'piezoelectric')`.
 * It does not depend on the setting. Throws a RangeError for an unknown key or name.
 */
export function allowsProperty(key: MagneticPointGroupKey, name: TensorPropertyName): boolean {
  return tensorForm(key, named(name), { setting: 1 }).basis.length > 0;
}

/** The named properties the point group allows, in the order of `TENSOR_PROPERTIES`. */
export function allowedProperties(key: MagneticPointGroupKey): readonly TensorPropertyName[] {
  return deepFreeze(TENSOR_PROPERTY_NAMES.filter((name) => allowsProperty(key, name)));
}

/**
 * True if the group generated by `operations` allows the named property, e.g. for the site
 * symmetry of a surface normal or the operations of a distorted crystal. The operations are read
 * and closed as `tensorFormOf` reads them, within the tolerance, and it throws a RangeError as
 * `tensorFormOf` does.
 */
export function allowsPropertyOf(
  operations: readonly CartesianOperation[],
  name: TensorPropertyName,
  options?: ToleranceOptions,
): boolean {
  checkOptions(options, TOLERANCE_KEYS, 'allowsPropertyOf');
  const checked = named(name);
  return allows(callerGroup(operations, options), checked);
}

/** The named properties the group generated by `operations` allows. Reads the operations as `allowsPropertyOf`. */
export function allowedPropertiesOf(
  operations: readonly CartesianOperation[],
  options?: ToleranceOptions,
): readonly TensorPropertyName[] {
  checkOptions(options, TOLERANCE_KEYS, 'allowedPropertiesOf');
  const group = callerGroup(operations, options);
  return deepFreeze(TENSOR_PROPERTY_NAMES.filter((name) => allows(group, name)));
}

function allows(group: IdealGroup, name: TensorPropertyName): boolean {
  const { spec, perms } = checkedSpec(name);
  return allowsTensor(group.operations, spec, perms);
}
