def change_of_coordinates(
    linear_part: ArrayLike,
    *,
    origin_shift: Optional[ArrayLike] = None,
    points: Optional[ArrayLike] = None,
    directions: Optional[ArrayLike] = None,
    planes: Optional[ArrayLike] = None,
    metric: Optional[ArrayLike] = None,
    operations: Optional[Operations | Sequence[Mapping[str, Any]]] = None,
    tolerance: Optional[float] = None,
) -> CoordinateChange:
    """Changes the coordinate system by the pair (P, p): the new basis is (a′, b′, c′) = (a, b, c)·P
    and the new origin lies at p. Transforms the given quantities by ITA's equations: point
    coordinates x′ = P⁻¹(x − p), vector coefficients [uvw]′ = P⁻¹[uvw], Miller indices (hkl)′ =
    (hkl)P, the metric tensor G′ = PᵀGP, and operations W′ = P⁻¹WP, w′ = P⁻¹(w + (W − I)p); and
    gives the inverse pair (Q, q) = (P⁻¹, −P⁻¹p). det P may be negative (a change of handedness,
    which ITA allows).

    P, p and the operations are read each number as the simplest fraction within the tolerance
    (default ``EPSILON``; 0.3333333 is 1/3) and transformed exactly, so that every result, the
    inverse pair included, can be passed back; the other quantities are floating point. P is
    rational in a change between lattice bases, as in ITA; an irrational P (a rotation by 30°) is
    read as the nearby fractions, about as exact as the tolerance, and a much smaller tolerance can
    make the exact products leave the safe integers, a SymcrysError. A transformed operation has a
    ``matrix`` and a ``translation`` alone: other fields of the record (``cartesian``, in the
    magnetic API ``time_reversal``) are not carried over, so they are matched by index. Raises
    SymcrysError for a singular P, a quantity of the wrong shape, an unknown quantity, an operation
    with det W ≠ ±1, and one whose W′ is not integral (the new basis does not span a lattice that
    the operation maps onto itself).

    Parameters
    ----------
    linear_part
        P, the linear part: its columns are the new basis vectors a′, b′, c′ in the old basis; det P
        ≠ 0, also negative.
    origin_shift : keyword-only, optional
        p, the origin shift: the coordinates of the new origin in the old coordinate system; default
        zero.
    points : keyword-only, optional
        Point coordinates x: x′ = P⁻¹(x − p).
    directions : keyword-only, optional
        Coefficients [uvw] of vectors, e.g. directions: [uvw]′ = P⁻¹[uvw]; not changed by the origin
        shift.
    planes : keyword-only, optional
        Miller indices (hkl) of planes: (hkl)′ = (hkl)P; not changed by the origin shift.
    metric : keyword-only, optional
        The metric tensor G: G′ = PᵀGP.
    operations : keyword-only, optional
        Operations (W, w): W′ = P⁻¹WP, w′ = P⁻¹(w + (W − I)p).
    tolerance : keyword-only, optional
        Two numbers closer than this count as equal; default ``EPSILON`` (10⁻⁵). It is measured per
        matrix entry for operations, as the distance of unit vectors for directions and per
        coordinate modulo the lattice for points (docs/conventions.md, "Tolerances").
    """
    result: CoordinateChange = _shared.convert(
        _call(
            "changeOfCoordinates",
            _shared.options(linear_part=linear_part, origin_shift=origin_shift),
            _shared.options(
                points=points,
                directions=directions,
                planes=planes,
                metric=metric,
                operations=None if operations is None else _shared.operation_list(operations, ("matrix",)),
            ),
            _shared.options(tolerance=tolerance),
        ),
        _S_CoordinateChange,
    )
    return result


def cell_transformation(
    bravais_lattice: str,
    from_cell: Mapping[str, Any],
    to_cell: Mapping[str, Any],
) -> CoordinateTransformation:
    """The change of the coordinate system from one cell of a lattice to another: P with (a′, b′,
    c′) = (a, b, c)·P, where (a, b, c) is the basis of ``from_cell`` and (a′, b′, c′) that of
    ``to_cell``, to be passed to ``change_of_coordinates`` (the origin stays). The change back is
    ``cell_transformation(bravais_lattice, to_cell, from_cell)``.

    A cell is named by its fields; a field left out takes the value of the conventional cell in the
    standard setting, so an empty cell is that cell. Where a lattice takes ``centring``, the
    centring of its conventional cell names that cell. The fields by Bravais lattice:

    mP and mS: ``unique_axis`` (``'a'``, ``'b'``, ``'c'``; standard ``'b'``) and ``cell_choice`` (1,
    2, 3; standard 1); in mS the cell choices of one unique axis are centred C, A, I (unique axis
    b), A, B, I (c) and B, C, I (a).

    oP, oS, oI and oF: ``setting``, ``'abc'`` (standard), ``'ba-c'``, ``'cab'``, ``'-cba'``,
    ``'bca'`` or ``'a-cb'``, the basis of the cell in the standard one; oI and oF also ``centring``
    ``'P'``, the primitive cell of the standard setting.

    tP: ``centring`` ``'C'`` and ``cell`` 1 or 2, the C-centred cells C₁, C₂. tI: ``centring``
    ``'F'`` and ``cell`` 1 or 2, the F-centred cells F₁, F₂, and ``centring`` ``'P'``, the primitive
    cell.

    hP: ``centring`` and ``cell``, ``'C'`` for the orthohexagonal cells C₁, C₂, C₃, ``'H'`` for the
    triple hexagonal cells H₁, H₂, H₃, ``'D'`` for the triple rhombohedral cells D₁, D₂.

    hR: ``axes`` ``'hexagonal'`` (standard) with ``cell`` 1, 2, 3 and ``setting`` ``'obverse'`` or
    ``'reverse'``, the triple hexagonal cells R₁, R₂, R₃ (standard R₁ obverse); ``axes``
    ``'rhombohedral'``, the primitive cell; ``centring`` ``'C'`` and ``cell`` 1, 2, 3, the C-centred
    monoclinic cells C₁, C₂, C₃, whose unique axes b₁, b₂, b₃ are the three twofold axes of the
    lattice, and ``centring`` ``'A'`` with ``cell``, the A-centred ones A₁, A₂, A₃, with unique axes
    c₁, c₂, c₃.

    cI and cF: ``centring`` ``'P'``, the primitive cell, the one ITA gives for the conventional
    cell.

    Fractions such as 1/3 are the nearest numbers, which ``change_of_coordinates`` reads back as
    fractions.
    """
    result: CoordinateTransformation = _shared.convert(
        _call(
            "cellTransformation",
            bravais_lattice,
            _shared.mapping(from_cell, "from_cell"),
            _shared.mapping(to_cell, "to_cell"),
        ),
        _S_CoordinateTransformation,
    )
    return result


