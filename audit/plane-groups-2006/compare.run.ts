/**
 * The 17 plane groups: symcrys (ITA 6th ed., 2016, Chapter 2.2) vs plane-groups (ITA 5th ed., 2006,
 * Part 6, pp. 92–109), symcrys#31.
 *
 * An additional, independent check of the transcription, not its anchor (the anchor is the 2016
 * print; GUIDE.md, "Correctness and tests"). Reads js/ebenengruppen.js from the sibling
 * checkout ../plane-groups and writes report.md next to this file. Run by hand: npm run
 * audit:plane-groups-2006. Not part of the build, the tests or CI.
 *
 * Compared per group: number, short and full symbol, point group, the symmetry operations as
 * printed (from the 2016 transcription in references/), the general position, the selected
 * generators, the asymmetric unit, and per Wyckoff position multiplicity, letter, oriented site
 * symmetry and coordinates.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { it } from 'vitest';
import { EBENENGRUPPEN } from '../../../plane-groups/js/ebenengruppen.js';
import { PLANE_GROUP_DATA } from '../../packages/ts/src/spaceGroups/planeGroupData.js';
import { formatOperation } from '../../packages/ts/src/spaceGroups/affine.js';
import { planeGroupFullSymbol, planeGroupOperations } from '../../packages/ts/src/spaceGroups/planeGroups.js';
import { planePointGroupOf } from '../../packages/ts/src/spaceGroups/planePointGroups.js';
import { planeWyckoffRows } from '../../packages/ts/src/spaceGroups/planeWyckoff.js';
import { parseAsymmetricUnit } from '../../packages/ts/src/testUtils/printedAsymmetricUnit.js';

const here = fileURLToPath(new URL('.', import.meta.url));
const app = new URL('../../../plane-groups/', import.meta.url);

/** The printed "Symmetry operations" of each group, from the 2016 transcription. */
function printedOperations(): Map<number, { ops: string[]; centred?: string[] }> {
  const md = readFileSync(new URL('../../references/itc/vol-a-2016-plane-groups.md', import.meta.url), 'utf8');
  const out = new Map<number, { ops: string[]; centred?: string[] }>();
  for (const section of md.split('\n## ').slice(1)) {
    const nr = Number(/^(\d+)/.exec(section)?.[1]);
    const list = (re: RegExp) =>
      re
        .exec(section)?.[1]
        .split('; ')
        .map((x) => x.replace(/^\(\d+\) /, ''));
    out.set(nr, {
      ops: list(/^Symmetry operations(?: for \(0,0\)\+ set)?: (.*?) *$/m) ?? [],
      centred: list(/^Symmetry operations for \(1\/2,1\/2\)\+ set: (.*?) *$/m),
    });
  }
  return out;
}

it('compares symcrys with plane-groups', () => {
  const printed = printedOperations();
  const diffs: string[] = [];
  let compared = 0;
  const same = (what: string, nr: number, a: unknown, b: unknown) => {
    compared++;
    if (JSON.stringify(a) !== JSON.stringify(b))
      diffs.push(`| ${nr} | ${what} | ${JSON.stringify(a)} | ${JSON.stringify(b)} |`);
  };
  for (const g of PLANE_GROUP_DATA) {
    const e = EBENENGRUPPEN.find((x: { nr: number }) => x.nr === g.number);
    if (!e) {
      diffs.push(`| ${g.number} | group | present | missing |`);
      continue;
    }
    // symcrys computes all but the symbol, the generators, the centring and the asymmetric unit.
    const ops = planeGroupOperations(g.symbol);
    const general = ops.slice(0, ops.length / (1 + g.centring.length)).map(formatOperation);
    same('symbol', g.number, g.symbol, e.symbol);
    same('full symbol', g.number, planeGroupFullSymbol(g.symbol), e.lang);
    same('point group', g.number, planePointGroupOf(g.symbol).key, e.punktgruppe);
    same('symmetry operations', g.number, printed.get(g.number)?.ops, e.opsText);
    same('symmetry operations (1/2,1/2)+', g.number, printed.get(g.number)?.centred, e.zentrText);
    same('general position', g.number, general, e.ops);
    // The generators by their number in the general position, as plane-groups gives them.
    same(
      'generators',
      g.number,
      g.generators.map((t) => general.indexOf(t) + 1),
      e.erzeugende,
    );
    // The stored inequalities against the text of plane-groups, read as the printed block.
    const unitText = e.ae.text.replace(/≤/g, '<=').replace(/−/g, '-');
    let unit: unknown;
    try {
      unit = parseAsymmetricUnit(unitText);
    } catch {
      unit = unitText;
    }
    same('asymmetric unit', g.number, g.asymmetricUnit, unit);
    same(
      'Wyckoff positions',
      g.number,
      planeWyckoffRows(g.symbol).map(([m, l, s, c]) => [m, l, s, c]),
      e.wyckoff.map((w: { n: number; b: string; sym: string; koord: string[] }) => [w.n, w.b, w.sym, w.koord]),
    );
  }
  const rev = execFileSync('git', ['-C', fileURLToPath(app), 'log', '-1', '--format=%h %cs'], {
    encoding: 'utf8',
  }).trim();
  const lines = [
    '# Plane groups: symcrys (ITA 2016) vs plane-groups (ITA 2006)',
    '',
    'Generated by `audit/plane-groups-2006/compare.run.ts` (npm run audit:plane-groups-2006), symcrys#31.',
    '',
    `- plane-groups ${rev}: \`js/ebenengruppen.js\` (ITA 5th ed., 2006, Part 6, pp. 92–109)`,
    '- symcrys: computed from `PLANE_GROUP_DATA` (generators, centring, asymmetric unit) and `references/itc/vol-a-2016-plane-groups.md` (ITA 6th ed., 2016, Chapter 2.2, pp. 176–192)',
    '',
    `Compared: ${compared} items over 17 groups (symbols, point group, symmetry operations, general position, generators, asymmetric unit, Wyckoff positions). Differences: ${diffs.length}.`,
    '',
    'Not compared: origin, vertices of the asymmetric unit and Patterson symmetry, which plane-groups',
    'does not hold in this form.',
    '',
  ];
  if (diffs.length)
    lines.push('| No. | What | symcrys (2016) | plane-groups (2006) |', '|---|---|---|---|', ...diffs, '');
  writeFileSync(`${here}report.md`, lines.join('\n'));
});
